def _build() -> tuple[tuple[tuple, ...], tuple[tuple, ...], tuple[tuple, ...]]:
    exam_rows: list[tuple] = []
    knowledge_exam_rows: list[tuple[int, int, int]] = []
    chapter_points: dict[int, list[int]] = {}
    for index, (chapter_id, knowledge_id, name) in enumerate(DATA):
        direction_id = EXAM_ID_BASE + index
        exam_rows.append((
            direction_id,
            name,
            f"{EXAM_CODE_PREFIX}_{index + 1:03d}",
            index + 1,
            SUBJECT_ID,
            chapter_id,
            None,
        ))
        knowledge_exam_rows.append((knowledge_id, direction_id, 0))
        points = chapter_points.setdefault(chapter_id, [])
        if knowledge_id not in points:
            points.append(knowledge_id)
    chapter_rows = tuple(
        (chapter_id, knowledge_id, order)
        for chapter_id, knowledge_ids in chapter_points.items()
        for order, knowledge_id in enumerate(knowledge_ids)
    )
    return tuple(exam_rows), tuple(knowledge_exam_rows), chapter_rows


EXAM_ROWS, KNOWLEDGE_EXAM_ROWS, CHAPTER_KNOWLEDGE_ROWS = _build()
