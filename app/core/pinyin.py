# 反查表：字 → 首字母
_INITIALS: dict[str, str] = {}
for _initial, _chars in _INITIAL_TABLE.items():
    for _char in _chars:
        _INITIALS.setdefault(_char, _initial)


def is_han(text: str) -> bool:
    """是不是汉字（按 Unicode 常用汉字区判断）。"""
    return "一" <= text <= "鿿"


def initials(text: str) -> str:
    """整串的拼音首字母。

    汉字取首字母（表外跳过），拉丁字母与数字原样小写保留，
    其它符号一律丢掉——搜索框里打什么符号都不该影响命中。
    """
    out: list[str] = []
    for char in str(text or ""):
        if is_han(char):
            initial = _INITIALS.get(char)
            if initial:
                out.append(initial)
            continue
        if char.isascii() and char.isalnum():
            out.append(char.lower())
    return "".join(out)
